"""Generate src/text/data.ts: PDF base encodings, a trimmed Adobe Glyph List and
the standard-14 font widths.

The source tables are the copies bundled with ReportLab (`pip install
reportlab`), which come from Adobe's published AFM metrics and the Adobe Glyph
List (https://github.com/adobe-type-tools/agl-aglfn, BSD-3-Clause).

    python3 packages/pdf/scripts/generate-data.py > packages/pdf/src/text/data.ts
"""

import json

from reportlab.pdfbase import _glyphlist
from reportlab.pdfbase._fontdata_enc_macroman import MacRomanEncoding
from reportlab.pdfbase._fontdata_enc_pdfdoc import PDFDocEncoding
from reportlab.pdfbase._fontdata_enc_standard import StandardEncoding
from reportlab.pdfbase._fontdata_enc_symbol import SymbolEncoding
from reportlab.pdfbase._fontdata_enc_winansi import WinAnsiEncoding
from reportlab.pdfbase._fontdata_enc_zapfdingbats import ZapfDingbatsEncoding
from reportlab.pdfbase import (
    _fontdata_widths_helvetica as helvetica,
    _fontdata_widths_helveticabold as helveticabold,
    _fontdata_widths_timesroman as timesroman,
    _fontdata_widths_timesbold as timesbold,
    _fontdata_widths_timesitalic as timesitalic,
    _fontdata_widths_timesbolditalic as timesbolditalic,
    _fontdata_widths_symbol as symbol,
    _fontdata_widths_zapfdingbats as zapfdingbats,
)

ENCODINGS = {
    "StandardEncoding": StandardEncoding,
    "WinAnsiEncoding": WinAnsiEncoding,
    "MacRomanEncoding": MacRomanEncoding,
    "PDFDocEncoding": PDFDocEncoding,
    "SymbolEncoding": SymbolEncoding,
    "ZapfDingbatsEncoding": ZapfDingbatsEncoding,
}

WIDTHS = {
    "Helvetica": helvetica.widths,
    "Helvetica-Bold": helveticabold.widths,
    "Times-Roman": timesroman.widths,
    "Times-Bold": timesbold.widths,
    "Times-Italic": timesitalic.widths,
    "Times-BoldItalic": timesbolditalic.widths,
    "Symbol": symbol.widths,
    "ZapfDingbats": zapfdingbats.widths,
}

RANGES = [
    (0x0020, 0x024F),  # Latin
    (0x02B0, 0x02FF),  # spacing modifiers
    (0x0370, 0x03FF),  # Greek
    (0x0400, 0x04FF),  # Cyrillic
    (0x2000, 0x27BF),  # punctuation, currency, letterlike, arrows, maths, shapes, dingbats
    (0xFB00, 0xFB06),  # Latin ligatures
]

encoded_names = {name for enc in ENCODINGS.values() for name in enc if name}

glyphs = {}
for name, uv in sorted(_glyphlist._glyphname2unicode.items()):
    if isinstance(uv, tuple):
        continue
    if name in encoded_names or any(lo <= uv <= hi for lo, hi in RANGES):
        glyphs[name] = uv


def encoding_ts(enc):
    return json.dumps(" ".join(name or "." for name in enc))


def widths_ts(widths):
    return json.dumps(" ".join(f"{name} {w}" for name, w in sorted(widths.items())))


out = []
out.append("// Generated by scripts/generate-data.py - do not edit by hand.")
out.append("//")
out.append("// Glyph names and widths come from Adobe's AFM metrics for the standard 14")
out.append("// fonts and the Adobe Glyph List (Copyright 2002-2019 Adobe, BSD-3-Clause,")
out.append("// https://github.com/adobe-type-tools/agl-aglfn).")
out.append("")
out.append("/** Base encodings: 256 space-separated glyph names, `.` for an unused code. */")
out.append("export const ENCODING_NAMES = {")
for key, enc in ENCODINGS.items():
    out.append(f"  {key}: {encoding_ts(enc)},")
out.append("} as const;")
out.append("")
out.append("/** Adobe Glyph List subset: `name hex` pairs, space separated. */")
out.append("export const GLYPH_LIST = " + json.dumps(" ".join(f"{n} {uv:04X}" for n, uv in glyphs.items())) + ";")
out.append("")
out.append("/** Standard-14 glyph widths (1/1000 em) as `name width` pairs; Courier is 600 throughout. */")
out.append("export const STANDARD_WIDTHS = {")
for key, widths in WIDTHS.items():
    out.append(f"  {json.dumps(key)}: {widths_ts(widths)},")
out.append("} as const;")
print("\n".join(out))
